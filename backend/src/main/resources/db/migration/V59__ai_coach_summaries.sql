-- V9 Phase 8 (AI-FR-18, AI-FR-21, AC-16): AI summaries for coaches, kept for
-- the week so reopening one costs nothing. scope PARTICIPANT has a
-- participant; scope COHORT has a cohort. A participant's summaries go with
-- their account; the coach's rating says whether a summary was accurate.
CREATE TABLE ai_coach_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope VARCHAR(20) NOT NULL,
    coach_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    participant_id BIGINT REFERENCES app_users(id) ON DELETE CASCADE,
    cohort_id BIGINT REFERENCES cohorts(id) ON DELETE CASCADE,
    week_start DATE NOT NULL,
    progress_text VARCHAR(2000),
    mood_text VARCHAR(2000),
    risks_text VARCHAR(2000),
    action_text VARCHAR(2000),
    accurate BOOLEAN,
    rating_note VARCHAR(1000),
    rated_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_coach_summaries_participant ON ai_coach_summaries (participant_id, week_start);
CREATE INDEX idx_ai_coach_summaries_cohort ON ai_coach_summaries (cohort_id, week_start);
