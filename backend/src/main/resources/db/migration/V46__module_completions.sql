-- V8 FR-72: a saved exercise. rows_json holds the rows of a form exercise and
-- stays null for a module proven by the user's existing data.
CREATE TABLE module_completions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    module_number INTEGER NOT NULL REFERENCES learning_modules(module_number),
    rows_json VARCHAR(20000),
    completed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_module_completions_user_module UNIQUE (user_id, module_number)
);
