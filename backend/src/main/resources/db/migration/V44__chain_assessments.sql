-- V8 FR-71: one score from 1 to 5 per chain, higher meaning it holds the user
-- back less. One assessment per day; the first row is the baseline.
CREATE TABLE chain_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    taken_on DATE NOT NULL,
    settling_score INTEGER NOT NULL,
    fear_score INTEGER NOT NULL,
    criticism_score INTEGER NOT NULL,
    vision_score INTEGER NOT NULL,
    knowledge_score INTEGER NOT NULL,
    resources_score INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_chain_assessments_user_date UNIQUE (user_id, taken_on)
);
