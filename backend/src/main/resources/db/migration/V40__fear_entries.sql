-- V8 FR-65: a dated log of fears, each paired with a low-risk first test.
-- ON DELETE SET NULL so permanently deleting a dream keeps the journal entry.
CREATE TABLE fear_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    fear VARCHAR(500) NOT NULL,
    worst_case VARCHAR(2000) NOT NULL,
    likelihood VARCHAR(20) NOT NULL,
    first_test VARCHAR(2000) NOT NULL,
    related_dream_id BIGINT REFERENCES dreams(id) ON DELETE SET NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_fear_entries_user ON fear_entries (user_id);
