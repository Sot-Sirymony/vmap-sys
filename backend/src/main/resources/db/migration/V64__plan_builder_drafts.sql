-- V11 Phase 2 (PB-FR-30, PB-FR-33, PB-NFR-09): the unfinished Build my plan
-- session for one dream, so leaving the page or changing device loses nothing
-- and asks Claude nothing again.
--
-- A draft is never plan data: dashboards, boards, exports, coach views and
-- share links read the plan tables, not this one. Only its owner reads it.
-- It is removed when the plan is added, when the participant discards it,
-- 14 days after its last change (daily job), with its dream, and with the account.
CREATE TABLE plan_builder_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    dream_id BIGINT NOT NULL REFERENCES dreams(id) ON DELETE CASCADE,
    stage VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_plan_builder_drafts_user_dream UNIQUE (user_id, dream_id)
);

CREATE INDEX idx_plan_builder_drafts_expires ON plan_builder_drafts (expires_at);
