-- V9 (v0.1 FR-01, FR-16, FR-17, FR-20): cohorts, coaches and coach comments.
-- A participant joins at most one cohort with its join code (D-7). A coach
-- reads only their own cohorts' participants (D-6), and journals only when the
-- participant shares them (D-8). Deleting a coach's account leaves their
-- cohorts and comments in place without a coach.
CREATE TABLE cohorts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    join_code VARCHAR(12) NOT NULL,
    coach_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    start_date DATE,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_cohorts_join_code UNIQUE (join_code)
);

CREATE INDEX idx_cohorts_coach ON cohorts (coach_id);

ALTER TABLE app_users ADD COLUMN cohort_id BIGINT REFERENCES cohorts(id);
ALTER TABLE app_users ADD COLUMN share_journals_with_coach BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX idx_app_users_cohort ON app_users (cohort_id);

-- user_id is the participant the comment is for, so it goes with their account.
CREATE TABLE coach_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    coach_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    target_type VARCHAR(20) NOT NULL,
    target_id BIGINT,
    body VARCHAR(2000) NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_coach_comments_user ON coach_comments (user_id);
