-- V8 FR-74: results reached along the way to a dream. They belong to the dream,
-- so they go with it when it is permanently deleted.
CREATE TABLE milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    dream_id BIGINT NOT NULL REFERENCES dreams(id) ON DELETE CASCADE,
    title VARCHAR(220) NOT NULL,
    achieved_on DATE NOT NULL,
    note VARCHAR(1000),
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_milestones_dream ON milestones (dream_id);
