-- PB-FR-36: one row per plan added from Build my plan, for requests and cost
-- per finished plan. Counts only, no text. Like the usage log, a deleted
-- account only loses its link to these rows; a deleted dream keeps them.
CREATE TABLE plan_builder_finished_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(id),
    dream_id BIGINT REFERENCES dreams(id) ON DELETE SET NULL,
    ai_requests INTEGER NOT NULL,
    ai_cost_usd NUMERIC(12, 6) NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_plan_builder_finished_plans_finished ON plan_builder_finished_plans (finished_at);
