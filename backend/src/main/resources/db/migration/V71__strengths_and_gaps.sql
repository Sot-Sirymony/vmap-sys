-- V8.1 Phase 5 (BRD v0.2, FR-79 to FR-84): the Strengths and Gaps profile.
-- Each item is one strength or weakness, with evidence, judged against one
-- dream. A high-relevance weakness gets one way of covering it; the record it
-- created (a partner, a plan step or an exercise row) is remembered so that
-- removing the gap can offer to remove it too.
CREATE TABLE self_assessment_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    dream_id BIGINT NOT NULL REFERENCES dreams(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL,
    description VARCHAR(300) NOT NULL,
    evidence VARCHAR(2000) NOT NULL,
    relevance VARCHAR(20) NOT NULL,
    source VARCHAR(20) NOT NULL,
    outside_by VARCHAR(160),
    outside_view VARCHAR(2000),
    outside_agrees BOOLEAN,
    cover_method VARCHAR(20),
    cover_note VARCHAR(1000),
    linked_partner_id BIGINT REFERENCES partners(id) ON DELETE SET NULL,
    linked_step_id BIGINT REFERENCES vision_steps(id) ON DELETE SET NULL,
    linked_module_number INTEGER,
    linked_module_row VARCHAR(4000),
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_self_assessment_items_user ON self_assessment_items (user_id);
CREATE INDEX idx_self_assessment_items_dream ON self_assessment_items (dream_id);

-- FR-84: each time the profile is saved, a copy of its active items (kind,
-- description, relevance and cover), so a later retake can show what changed.
CREATE TABLE self_assessment_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    dream_id BIGINT NOT NULL REFERENCES dreams(id) ON DELETE CASCADE,
    taken_on DATE NOT NULL,
    items_json VARCHAR(20000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_self_assessment_snapshots_user_dream ON self_assessment_snapshots (user_id, dream_id);
