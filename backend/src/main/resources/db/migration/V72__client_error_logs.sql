-- Diagnostics: requests that failed in the browser, recorded by the page that
-- made them (first the Strengths and Gaps page). Lets an admin see that a page
-- is broken in production, for example a frontend calling an endpoint the
-- deployed backend does not have yet, without waiting for a user to report it.
--
-- Append-only: the app adds rows and reads them, and removes them only with
-- the account. Never stored here: request or response bodies, tokens, query
-- strings, or any text the user typed. The message is the server's own error
-- message, cut to 500 characters.
CREATE TABLE client_error_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    page VARCHAR(40) NOT NULL,
    method VARCHAR(10) NOT NULL,
    path VARCHAR(300) NOT NULL,
    status INTEGER NOT NULL,
    message VARCHAR(500),
    reference VARCHAR(40),
    app_version VARCHAR(40)
);

CREATE INDEX idx_client_error_logs_user_page_time ON client_error_logs (user_id, page, occurred_at);
CREATE INDEX idx_client_error_logs_time ON client_error_logs (occurred_at);
