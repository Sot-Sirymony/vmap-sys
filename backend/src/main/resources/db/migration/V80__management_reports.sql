-- V19 phase 2 (BRD 19.0.0, RM-FR-16 to RM-FR-31, D-19-1, D-19-2): saved
-- Management Reports. A Draft reads the live plan with its scope, period and
-- filters; Final freezes the figures in `snapshot` and never recalculates.
--
-- The snapshot is gzip-compressed JSON, stored as base64 TEXT so tests on H2
-- and production on PostgreSQL behave the same (RM-NFR-06: at most 5 MB). It
-- holds only the report's allow-listed fields (D-19-2). `snapshot_checksum`
-- is the SHA-256 of the uncompressed JSON (RM-NFR-04).
--
-- Rollback:
--   DROP TABLE management_reports;
CREATE TABLE management_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    code VARCHAR(20) NOT NULL,
    name VARCHAR(120) NOT NULL,
    scope_kind VARCHAR(10) NOT NULL,
    area_id BIGINT REFERENCES vision_areas(id) ON DELETE SET NULL,
    dream_id BIGINT REFERENCES dreams(id) ON DELETE SET NULL,
    scope_label VARCHAR(255),
    period_kind VARCHAR(20) NOT NULL,
    period_from DATE,
    period_to DATE,
    filters TEXT,
    status VARCHAR(10) NOT NULL,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    compare_to_report_id BIGINT REFERENCES management_reports(id) ON DELETE SET NULL,
    highlights VARCHAR(2000),
    risks VARCHAR(2000),
    decisions_needed VARCHAR(2000),
    nothing_needed BOOLEAN NOT NULL DEFAULT FALSE,
    next_focus VARCHAR(2000),
    goal_notes TEXT,
    sections TEXT,
    language VARCHAR(5) NOT NULL DEFAULT 'en',
    snapshot TEXT,
    snapshot_version INTEGER,
    snapshot_checksum VARCHAR(64),
    finalized_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_management_reports_user_code UNIQUE (user_id, code)
);

CREATE INDEX idx_management_reports_user ON management_reports (user_id, archived);
