-- V8 FR-72: the fifteen modules. Order lives in position so it can change
-- without code, and text lives per language so Khmer can be added beside it.
-- All wording here is original to this application.
CREATE TABLE learning_modules (
    module_number INTEGER PRIMARY KEY,
    position INTEGER NOT NULL UNIQUE,
    stage VARCHAR(20) NOT NULL,
    completion_rule VARCHAR(30) NOT NULL,
    link_path VARCHAR(120)
);

CREATE TABLE learning_module_content (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_number INTEGER NOT NULL REFERENCES learning_modules(module_number),
    language VARCHAR(10) NOT NULL,
    title VARCHAR(160) NOT NULL,
    summary VARCHAR(600) NOT NULL,
    guidance VARCHAR(3000) NOT NULL,
    exercise_instructions VARCHAR(1000) NOT NULL,
    fields_json VARCHAR(2000),
    CONSTRAINT uq_learning_module_content UNIQUE (module_number, language)
);

