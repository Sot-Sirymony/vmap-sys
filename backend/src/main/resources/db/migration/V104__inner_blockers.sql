-- V34 (BRD 34, D-34-1 to D-34-10): the participant's own inner blockers, each with
-- how it shows up and a short practice, and the weekly answer "did the practice help?".

CREATE TABLE inner_blockers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    blocker VARCHAR(120) NOT NULL,
    shows_up VARCHAR(500),
    practice VARCHAR(300) NOT NULL,
    -- D-34-3: one of the six chain score keys, or none.
    chain_key VARCHAR(32),
    -- D-34-3: null means "for all my dreams".
    dream_id BIGINT REFERENCES dreams(id) ON DELETE SET NULL,
    -- D-34-6: the daily habit made from the practice.
    habit_id BIGINT REFERENCES habits(id) ON DELETE SET NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    resolved_at TIMESTAMP WITH TIME ZONE,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_inner_blockers_status CHECK (status IN ('ACTIVE', 'RESOLVED')),
    CONSTRAINT ck_inner_blockers_chain CHECK (chain_key IS NULL OR chain_key IN
        ('settlingScore', 'fearScore', 'criticismScore', 'prioritiesScore', 'persistenceScore', 'visionScore'))
);

CREATE INDEX idx_inner_blockers_user ON inner_blockers (user_id, archived, status);

-- D-34-10: one answer per blocker per weekly review.
CREATE TABLE inner_blocker_checkins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    inner_blocker_id BIGINT NOT NULL REFERENCES inner_blockers(id) ON DELETE CASCADE,
    review_id BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    answer VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_inner_blocker_checkins UNIQUE (inner_blocker_id, review_id),
    CONSTRAINT ck_inner_blocker_checkins_answer CHECK (answer IN ('YES', 'PARTLY', 'NO', 'NOT_DONE'))
);

CREATE INDEX idx_inner_blocker_checkins_review ON inner_blocker_checkins (review_id);
