-- V8 FR-65: one attitude score per user per day. The unique constraint also
-- serves the "latest check-ins" read.
CREATE TABLE attitude_checkins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    check_in_date DATE NOT NULL,
    score INTEGER NOT NULL,
    note VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_attitude_checkins_user_date UNIQUE (user_id, check_in_date)
);
