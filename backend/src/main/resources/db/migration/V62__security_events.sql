-- V10 (SEC-09-01 to SEC-09-03, SEC-08-06): the security event log.
--
-- Append-only: the app has no way to change or delete a row, except the daily
-- job that removes rows older than the retention period (12 months by default).
-- No API, admin screen or account action edits it.
--
-- actor_id is deliberately not a foreign key and not named user_id: when an
-- account is deleted its own data goes, but the record of what happened to and
-- through it stays, as an audit trail must. It holds the account's number only.
--
-- Never stored here: passwords, tokens, API keys, email addresses, or any text
-- of a dream, journal or message. A failed sign-in for an email records only a
-- SHA-256 of the address (subject_hash), enough to count attacks on one account.
CREATE TABLE security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_type VARCHAR(60) NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    actor_id BIGINT,
    subject_hash VARCHAR(64),
    ip_address VARCHAR(64),
    target_type VARCHAR(40),
    target_id BIGINT,
    detail VARCHAR(300)
);

CREATE INDEX idx_security_events_time ON security_events (occurred_at);
CREATE INDEX idx_security_events_type_time ON security_events (event_type, occurred_at);
CREATE INDEX idx_security_events_actor_time ON security_events (actor_id, occurred_at);
CREATE INDEX idx_security_events_subject_time ON security_events (subject_hash, occurred_at);
CREATE INDEX idx_security_events_ip_time ON security_events (ip_address, occurred_at);
