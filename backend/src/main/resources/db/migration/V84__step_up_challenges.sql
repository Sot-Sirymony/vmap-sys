-- V20 (BRD 20.0.0, SV-FR-10 to SV-FR-19): "Verify it's you" codes sent by
-- email before a risky action. Only an HMAC of the code is kept (SV-NFR-01).
-- A challenge belongs to one person, one session and one kind of action, and,
-- for a new reminder address, to that address (target_hash, D-20-2).
CREATE TABLE step_up_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    session_id BIGINT NOT NULL REFERENCES auth_sessions(id) ON DELETE CASCADE,
    action VARCHAR(40) NOT NULL,
    target_hash VARCHAR(64),
    code_hash VARCHAR(64) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMP NOT NULL,
    verified_at TIMESTAMP,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_step_up_challenges_user ON step_up_challenges (user_id, created_at);
CREATE INDEX idx_step_up_challenges_session ON step_up_challenges (session_id, action);

-- D-20-3: the 10-minute verified window for the settings group of actions.
ALTER TABLE auth_sessions ADD COLUMN verified_until TIMESTAMP;
