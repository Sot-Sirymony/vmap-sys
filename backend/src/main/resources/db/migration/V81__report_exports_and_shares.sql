-- V19 phase 4 (BRD 19.0.0, RM-FR-25, RM-FR-46 to RM-FR-52): each saved
-- report's download history, and read-only share links to final reports.
--
-- A share link keeps only a SHA-256 of its token, like V9 plan shares; the
-- token is shown once, when the link is made. `sections` is a JSON list of
-- the report sections the reviewer sees. Both tables carry user_id so an
-- account is deleted in one pass (AccountService), and both go with their
-- report.
--
-- Rollback:
--   DROP TABLE report_share_links;
--   DROP TABLE report_exports;
CREATE TABLE report_exports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    report_id BIGINT NOT NULL REFERENCES management_reports(id) ON DELETE CASCADE,
    format VARCHAR(10) NOT NULL,
    language VARCHAR(5) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_report_exports_report ON report_exports (report_id, created_at);

CREATE TABLE report_share_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    report_id BIGINT NOT NULL REFERENCES management_reports(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    sections TEXT NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    view_count INTEGER NOT NULL DEFAULT 0,
    last_viewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_report_share_links_report ON report_share_links (report_id);
