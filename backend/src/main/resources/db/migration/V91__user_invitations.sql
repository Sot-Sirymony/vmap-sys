-- V23 (BRD 23.0.0) phase 5: invitations for accounts an admin creates
-- (UM-FR-24, D-23-5). The person chooses their own password from a single-use
-- link; nobody else ever knows it.
--
-- Like password_reset_tokens, only a SHA-256 of the emailed token is kept, so
-- reading this table opens no account. used_at is set on acceptance, or when a
-- newer invitation replaces this one, so a replayed link can be refused.
CREATE TABLE user_invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    -- The admin who sent it; empty if that admin's account is later deleted.
    created_by_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_invitations_hash UNIQUE (token_hash)
);

CREATE INDEX idx_user_invitations_user ON user_invitations (user_id);
