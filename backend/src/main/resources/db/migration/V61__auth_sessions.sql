-- V10 (SEC-07-03, SEC-07-04): one row per sign-in, so a session can be ended
-- on the server. The short-lived access token names its session (claim "sid"),
-- and every request checks the session is still open: logging out, a password
-- change or reset, or reuse of a stolen refresh token ends it at once.
--
-- The refresh token itself is never stored, only its SHA-256, for the same
-- reason as password_reset_tokens. It is replaced on every use; the one before
-- it is kept in previous_token_hash, so a second use of an old token can be
-- recognised: within a few seconds it is two tabs refreshing together, later
-- it means the token was copied, and the session is ended.
CREATE TABLE auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    refresh_token_hash VARCHAR(64) NOT NULL,
    previous_token_hash VARCHAR(64),
    rotated_at TIMESTAMP WITH TIME ZONE,
    remember_me BOOLEAN NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    revoked_reason VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_auth_sessions_refresh_hash UNIQUE (refresh_token_hash)
);

CREATE INDEX idx_auth_sessions_user ON auth_sessions (user_id);
CREATE INDEX idx_auth_sessions_previous_hash ON auth_sessions (previous_token_hash);
