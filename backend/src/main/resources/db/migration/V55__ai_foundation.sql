-- V9 Phase 3: the AI foundation. Consent (AI-NFR-03), Dream Coach chat history
-- (AI-FR-25), the usage log (AI-NFR-14), crisis alerts (AI-NFR-09) and the
-- limits that keep spend inside the monthly budget (AI-NFR-15).

-- AI-NFR-03: one consent covers dreams, plans and journals (D-2). Null means
-- no consent, so AI stays off for that person.
ALTER TABLE app_users ADD COLUMN ai_consent_at TIMESTAMP WITH TIME ZONE;

-- The consent record the Data Protection Officer needs: every give and withdraw.
CREATE TABLE ai_consent_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    action VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_consent_events_user ON ai_consent_events (user_id);

-- AI-NFR-14: one row per Claude call, with cost and rating but no conversation
-- text. Deleting an account clears user_id rather than the row, so the month's
-- spend still counts against the budget.
CREATE TABLE ai_usage_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    feature VARCHAR(40) NOT NULL,
    model VARCHAR(60),
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    cost_usd NUMERIC(12, 6) NOT NULL DEFAULT 0,
    outcome VARCHAR(30) NOT NULL,
    rating INTEGER,
    rating_comment VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_usage_logs_created ON ai_usage_logs (created_at);

-- AI-FR-25: kept until the participant deletes them or their account.
CREATE TABLE ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    title VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_conversations_user ON ai_conversations (user_id);

CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    safety_flag VARCHAR(20),
    usage_log_id BIGINT REFERENCES ai_usage_logs(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_messages_conversation ON ai_messages (conversation_id);
CREATE INDEX idx_ai_messages_user_created ON ai_messages (user_id, created_at);

-- AI-NFR-09 (D-5): a crisis message alerts the participant's coach. The alert
-- says when, not what: the conversation stays private.
CREATE TABLE ai_safety_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    coach_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    alert_type VARCHAR(20) NOT NULL,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    acknowledged_by BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_safety_alerts_coach ON ai_safety_alerts (coach_id);

-- AI-NFR-15: a per-person daily limit so one person cannot use the whole
-- budget. AI-NFR-09: the help lines shown in a crisis; the safeguarding lead
-- must check them for each participant country.
ALTER TABLE ai_settings ADD COLUMN daily_message_limit INTEGER NOT NULL DEFAULT 20;
ALTER TABLE ai_settings ADD COLUMN help_lines VARCHAR(2000) NOT NULL DEFAULT
    'Cambodia emergency: police 117, ambulance 119. Child Helpline Cambodia: 1280. Outside Cambodia, find a free, confidential helpline at findahelpline.com.';
