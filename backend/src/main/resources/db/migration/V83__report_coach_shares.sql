-- V19 (BRD 19.0.0, RM-FR-50, decision D-19-3): a participant shares one final
-- report with their coach, read-only. One share per report: a participant has
-- one coach at a time. Deleted with the report, the participant or the coach.
CREATE TABLE report_coach_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    report_id BIGINT NOT NULL REFERENCES management_reports(id) ON DELETE CASCADE,
    coach_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    sections TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_report_coach_shares_report UNIQUE (report_id)
);
CREATE INDEX idx_report_coach_shares_coach ON report_coach_shares (coach_id, user_id);
