-- V9 Phase 9 (AI-FR-24, AI-FR-26): admin control of AI without code.
-- AI per cohort, on by default (answers the BRD's open question); an admin
-- can switch a cohort off and AI then stays off for its members.
ALTER TABLE cohorts ADD COLUMN ai_enabled BOOLEAN NOT NULL DEFAULT TRUE;

-- The program's own coaching guidelines, added to the built-in ones. The
-- built-in safety rules always stay; an admin cannot remove them.
ALTER TABLE ai_settings ADD COLUMN coaching_guidelines VARCHAR(4000);

-- AI-FR-26: resources and links an admin has checked. Resource ideas prefer
-- them, and only they may carry a link (AI-FR-13).
CREATE TABLE ai_approved_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(20) NOT NULL,
    name VARCHAR(200) NOT NULL,
    url VARCHAR(500),
    description VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
