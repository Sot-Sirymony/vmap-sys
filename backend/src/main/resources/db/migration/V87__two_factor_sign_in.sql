-- V21 (BRD 21.0.0): two-factor sign-in. Phase 1 adds the data only; signing in
-- does not change until phase 2.

-- One row per account that has 2FA on, or is setting it up (enabled_at null).
-- The authenticator secret is sealed with SecretCipher (TF-NFR-01);
-- last_totp_step stops a seen code being used twice (TF-FR-13).
CREATE TABLE two_factor_settings (
    user_id BIGINT PRIMARY KEY REFERENCES app_users(id),
    method VARCHAR(10) NOT NULL,
    totp_secret VARCHAR(512),
    last_totp_step BIGINT,
    enabled_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

-- TF-FR-04, TF-FR-07, TF-FR-15: ten single-use codes, kept only as an HMAC.
CREATE TABLE two_factor_recovery_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    code_hash VARCHAR(64) NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_two_factor_recovery_codes_user ON two_factor_recovery_codes (user_id);

-- TF-FR-10, TF-FR-11: the step between the first factor and the second. No
-- session exists yet. Only hashes of the token and of any email code are kept.
CREATE TABLE sign_in_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    method VARCHAR(10) NOT NULL,
    code_hash VARCHAR(64),
    attempts INTEGER NOT NULL DEFAULT 0,
    remember_me BOOLEAN NOT NULL,
    return_path VARCHAR(512) NOT NULL,
    origin VARCHAR(10) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_sign_in_challenges_token UNIQUE (token_hash)
);
CREATE INDEX idx_sign_in_challenges_user ON sign_in_challenges (user_id, created_at);
CREATE INDEX idx_sign_in_challenges_expires ON sign_in_challenges (expires_at);

-- TF-FR-21 to TF-FR-26: browsers remembered for 30 days; only the SHA-256 of
-- the device token is kept.
CREATE TABLE trusted_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash VARCHAR(64) NOT NULL,
    label VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    last_used_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    removed_at TIMESTAMP,
    CONSTRAINT uq_trusted_devices_token UNIQUE (token_hash)
);
CREATE INDEX idx_trusted_devices_user ON trusted_devices (user_id);

-- TF-FR-32: the set-up-by date for admins and coaches (D-21-2).
ALTER TABLE app_users ADD COLUMN two_factor_due_at TIMESTAMP;
