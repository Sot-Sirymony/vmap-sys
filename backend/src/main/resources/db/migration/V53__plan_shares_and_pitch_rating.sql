-- V9 (v0.1 FR-10): a participant shares one dream's plan with a partner or
-- mentor through a link, read-only and opt-in. Only a SHA-256 of the link's
-- token is stored, so a stored row cannot be turned back into a working link.
-- A share belongs to its dream, so it goes with it when the dream is
-- permanently deleted; deleting the partner only removes the label.
CREATE TABLE plan_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    dream_id BIGINT NOT NULL REFERENCES dreams(id) ON DELETE CASCADE,
    partner_id BIGINT REFERENCES partners(id) ON DELETE SET NULL,
    token_hash VARCHAR(64) NOT NULL,
    message VARCHAR(1000),
    expires_at TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    last_viewed_at TIMESTAMP WITH TIME ZONE,
    view_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_plan_shares_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_plan_shares_user_dream ON plan_shares (user_id, dream_id);

