-- V14 (BRD 14.0.0, GA-FR-28 to GA-FR-30): Sign in with Google.

-- GA-FR-28: one row per linked outside account. The Google account is known by
-- its permanent "sub", never by email alone (GA-FR-13). One Google account maps
-- to one app account, and an app account has at most one Google link.
CREATE TABLE external_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    provider VARCHAR(20) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    email_at_link VARCHAR(255) NOT NULL,
    last_email VARCHAR(255) NOT NULL,
    linked_at TIMESTAMP NOT NULL,
    last_used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_external_identities_subject UNIQUE (provider, subject),
    CONSTRAINT uq_external_identities_user UNIQUE (user_id, provider)
);

-- GA-FR-29: a started Google sign-in (10 minutes, used once). Only a SHA-256 of
-- the state is kept; the PKCE verifier is sealed with SecretCipher.
CREATE TABLE oauth_login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_hash VARCHAR(64) NOT NULL,
    code_verifier VARCHAR(512) NOT NULL,
    nonce VARCHAR(128) NOT NULL,
    remember_me BOOLEAN NOT NULL,
    return_path VARCHAR(512) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_oauth_login_attempts_state UNIQUE (state_hash)
);
CREATE INDEX idx_oauth_login_attempts_expires ON oauth_login_attempts (expires_at);

-- GA-FR-30: the one-time code handed to the frontend after Google answers:
-- SIGN_IN (60 seconds) or LINK (10 minutes, bound to a Google sub and account).
-- Only a SHA-256 of the code is kept.
CREATE TABLE oauth_handoffs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash VARCHAR(64) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    provider_subject VARCHAR(255) NOT NULL,
    remember_me BOOLEAN NOT NULL,
    return_path VARCHAR(512) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_oauth_handoffs_code UNIQUE (code_hash)
);
CREATE INDEX idx_oauth_handoffs_user ON oauth_handoffs (user_id);
CREATE INDEX idx_oauth_handoffs_expires ON oauth_handoffs (expires_at);
