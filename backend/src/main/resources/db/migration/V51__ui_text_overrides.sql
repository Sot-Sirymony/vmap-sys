-- V8 FR-20: interface text an admin has changed, per language. The app's own
-- text (English, and Khmer from km.ts) is the default; a row here replaces one
-- string for every account on this server. Deleting a row restores the default.
CREATE TABLE ui_text_overrides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language VARCHAR(10) NOT NULL,
    source_text VARCHAR(1000) NOT NULL,
    text VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ui_text_overrides UNIQUE (language, source_text)
);
